interface LangContextValue {
  lang: LangCode;
  setLang: (code: LangCode) => void;
  t: (key: string) => string;
  isRtl: boolean;
  current: LangOption;
}

export const LangContext = createContext<LangContextValue | null>(null);
const STORAGE_KEY = "ds_lang";

export function LangProvider({ children }: { children: ReactNode }) {
  const [lang, setLangState] = useState<LangCode>(() => {
    try {
      const stored = (typeof localStorage !== "undefined" ? localStorage.getItem(STORAGE_KEY) : null) as LangCode | null;
      if (stored && translations[stored]) return stored;
    } catch {
      /* storage unavailable (SSR / private mode) — default to English */
    }
    return "en";
  });

  const setLang = (code: LangCode) => {
    localStorage.setItem(STORAGE_KEY, code);
    setLangState(code);
  };

  const current = LANGUAGES.find(l => l.code === lang) ?? LANGUAGES[0];
  const t = (key: string): string => translations[lang]?.[key] ?? translations.en[key] ?? key;

  return (
    <LangContext.Provider value={{ lang, setLang, t, isRtl: current.rtl, current }}>
      <div dir={current.rtl ? "rtl" : "ltr"} lang={lang}>
        {children}
      </div>
    </LangContext.Provider>
  );
}

